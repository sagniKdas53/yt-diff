import pg from "pg";
import { DataTypes, Model, Sequelize } from "sequelize";
import type {
  CreationOptional,
  InferAttributes,
  InferCreationAttributes,
} from "sequelize";

import { config } from "../config.ts";
import { logger } from "../logger.ts";

export const sequelize = new Sequelize({
  host: config.db.host,
  dialect: "postgres",
  dialectModule: pg,
  logging: false,
  username: config.db.user,
  password: config.db.password as string,
  database: config.db.name,
  pool: {
    max: 15,
    min: 0,
    acquire: 30000,
    idle: 10000,
  },
});

export class VideoMetadata extends Model<
  InferAttributes<VideoMetadata>,
  InferCreationAttributes<VideoMetadata>
> {
  declare videoUrl: string;
  declare videoId: string;
  declare title: string;
  declare approximateSize: number | string;
  declare downloadStatus: CreationOptional<boolean>;
  declare isAvailable: CreationOptional<boolean>;
  declare fileName: CreationOptional<string | null>;
  declare thumbNailFile: CreationOptional<string | null>;
  declare onlineThumbnail: CreationOptional<string | null>;
  declare subTitleFile: CreationOptional<string | null>;
  declare commentsFile: CreationOptional<string | null>;
  declare descriptionFile: CreationOptional<string | null>;
  declare isMetaDataSynced: CreationOptional<boolean>;
  declare saveDirectory: CreationOptional<string | null>;
  declare raw_metadata: CreationOptional<unknown>;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
}

VideoMetadata.init({
  videoUrl: {
    type: DataTypes.STRING,
    allowNull: false,
    primaryKey: true,
  },
  videoId: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: "YouTube/platform-specific video identifier",
  },
  title: {
    type: DataTypes.STRING,
    allowNull: false,
  },
  approximateSize: {
    type: DataTypes.BIGINT,
    allowNull: false,
    comment: "Estimated file size in bytes",
  },
  downloadStatus: {
    type: DataTypes.BOOLEAN,
    allowNull: false,
    defaultValue: false,
    comment: "Whether video has been downloaded",
  },
  isAvailable: {
    type: DataTypes.BOOLEAN,
    allowNull: false,
    defaultValue: true,
    comment: "Whether video is still available on platform",
  },
  fileName: {
    type: DataTypes.STRING,
    allowNull: true,
    comment:
      "Name of the file on disk, should have the extension. null if not downloaded.",
  },
  thumbNailFile: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: "Thumbnail generated by yt-dlp",
  },
  onlineThumbnail: {
    type: DataTypes.TEXT,
    allowNull: true,
    comment:
      "Online thumbnail URL scraped from yt-dlp, used as fallback when thumbNailFile is not available. TEXT type because some CDN URLs exceed 255 chars.",
  },
  subTitleFile: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: "Subtitle generated by yt-dlp",
  },
  commentsFile: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: "Comments file generated by yt-dlp",
  },
  descriptionFile: {
    type: DataTypes.STRING,
    allowNull: true,
    comment:
      "Description retrieved by yt-dlp, not sure yet if I will save the path or read the data and save it here.",
  },
  isMetaDataSynced: {
    type: DataTypes.BOOLEAN,
    allowNull: false,
    defaultValue: false,
    comment:
      "This will serve as a marker for other processes to know if they need to sync metadata from downloaded files",
  },
  saveDirectory: {
    type: DataTypes.STRING,
    allowNull: true,
    defaultValue: null,
    comment:
      "Directory relative to saveLocation where files are stored. null if not downloaded, empty string for root.",
  },
  raw_metadata: {
    type: DataTypes.JSONB,
    allowNull: true,
    comment:
      "Full pruned yt-dlp JSON output for future use (tags, age rating, etc). Bulky arrays like formats/thumbnails/subtitles are removed before storage.",
  },
  createdAt: {
    type: DataTypes.DATE,
    allowNull: false,
  },
  updatedAt: {
    type: DataTypes.DATE,
    allowNull: false,
  },
}, {
  sequelize,
  modelName: "video_metadata",
  defaultScope: {
    attributes: { exclude: ["raw_metadata"] },
  },
  indexes: [
    {
      fields: ["videoId"],
      unique: false,
      name: "idx_video_metadata_video_id",
    },
  ],
});

