/**
 * One chat-bot request, from the message that arrived to the file that was
 * delivered.
 *
 * Kept deliberately separate from VideoMetadata so that submission history
 * survives a video being deleted from the web UI, and so the retention reaper
 * can tell — in SQL rather than by convention — which files the bot actually
 * fetched versus which already existed when it was asked.
 */
export class BotSubmission extends Model<
  InferAttributes<BotSubmission>,
  InferCreationAttributes<BotSubmission>
> {
  declare id: CreationOptional<string>;
  declare platform: string;
  declare chatId: string;
  declare messageId: CreationOptional<string | null>;
  declare requestedUrl: string;
  declare canonicalUrl: CreationOptional<string | null>;
  declare kind: string;
  declare playlistUrl: CreationOptional<string | null>;
  declare status: CreationOptional<string>;
  declare deliveryMode: CreationOptional<string | null>;
  declare retention: CreationOptional<string>;
  declare downloadedByBot: CreationOptional<boolean>;
  declare expiresAt: CreationOptional<Date | null>;
  declare errorMessage: CreationOptional<string | null>;
  declare createdAt: CreationOptional<Date>;
  declare updatedAt: CreationOptional<Date>;
}

BotSubmission.init({
  id: {
    type: DataTypes.UUID,
    defaultValue: DataTypes.UUIDV4,
    primaryKey: true,
    allowNull: false,
  },
  platform: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: 'Originating chat platform: "telegram" or "discord"',
  },
  chatId: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: "Platform chat/channel the request came from",
  },
  messageId: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: "Acknowledgement message edited in place as the request advances",
  },
  requestedUrl: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: "URL exactly as the user typed it",
  },
  canonicalUrl: {
    type: DataTypes.STRING,
    allowNull: true,
    references: {
      model: VideoMetadata,
      key: "videoUrl",
    },
    onUpdate: "CASCADE",
    // SET NULL, not CASCADE: deleting a video from the web UI must not erase
    // the record that the bot was once asked for it.
    onDelete: "SET NULL",
    comment: "Result of normalizeUrl(); foreign key linking to VideoMetadata",
  },
  kind: {
    type: DataTypes.STRING,
    allowNull: false,
    comment: 'Whether the request was for a "video" or a "playlist"',
  },
  playlistUrl: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: "Playlist this submission belongs to, when applicable",
  },
  status: {
    type: DataTypes.STRING,
    allowNull: false,
    defaultValue: "pending",
    comment: "pending | indexing | downloading | delivered | failed | reaped",
  },
  deliveryMode: {
    type: DataTypes.STRING,
    allowNull: true,
    comment: 'How the file reached the user: "upload" or "signed_url"',
  },
  retention: {
    type: DataTypes.STRING,
    allowNull: false,
    defaultValue: "ephemeral",
    comment: '"ephemeral" (reaped after expiry) or "persistent"',
  },
  downloadedByBot: {
    type: DataTypes.BOOLEAN,
    allowNull: false,
    defaultValue: false,
    comment:
      "False when the file already existed; the reaper never deletes those",
  },
  expiresAt: {
    type: DataTypes.DATE,
    allowNull: true,
    comment: "Null when persistent or when downloadedByBot is false",
  },
  errorMessage: {
    type: DataTypes.TEXT,
    allowNull: true,
    comment: "Reason recorded alongside status='failed'",
  },
  createdAt: {
    type: DataTypes.DATE,
    allowNull: false,
  },
  updatedAt: {
    type: DataTypes.DATE,
    allowNull: false,
  },
}, {
  sequelize,
  modelName: "bot_submission",
  indexes: [
    {
      // Drives the retention reaper's selection.
      fields: ["status", "expiresAt"],
    },
    {
      // Drives the submit-path dedupe lookup.
      fields: ["canonicalUrl"],
    },
  ],
});

PlaylistVideoMapping.belongsTo(VideoMetadata, {
  foreignKey: "videoUrl",
});

PlaylistVideoMapping.belongsTo(PlaylistMetadata, {
  foreignKey: "playlistUrl",
});

VideoMetadata.hasMany(PlaylistVideoMapping, {
  foreignKey: "videoUrl",
});

PlaylistMetadata.hasMany(PlaylistVideoMapping, {
  foreignKey: "playlistUrl",
});

export async function initializeDatabase() {
  try {
    await sequelize.authenticate();
    logger.info("Connection to database has been established successfully", {
      host: config.db.host,
      database: config.db.name,
    });
  } catch (error) {
    logger.error("Unable to connect to the database", {
      host: config.db.host,
      database: config.db.name,
      error: (error as Error).message,
    });
    throw error;
  }

  try {
    await sequelize.sync({ alter: true });

    logger.info("tables exist or are created successfully", {
      host: config.db.host,
      database: config.db.name,
      tables: JSON.stringify([
        VideoMetadata.name,
        PlaylistMetadata.name,
        PlaylistVideoMapping.name,
        BotSubmission.name,
      ]),
    });

    try {
      await sequelize.query("CREATE EXTENSION IF NOT EXISTS pg_trgm;");
      await sequelize.query(
        "CREATE INDEX IF NOT EXISTS idx_video_metadata_title_trgm ON video_metadata USING gin (title gin_trgm_ops);",
      );
      await sequelize.query(
        "CREATE INDEX IF NOT EXISTS idx_playlist_metadata_title_trgm ON playlist_metadata USING gin (title gin_trgm_ops);",
      );
      await sequelize.query(
        'CREATE INDEX IF NOT EXISTS idx_video_metadata_video_id ON video_metadata ("videoId");',
      );
      logger.info(
        "Trigram indexes and videoId index checked/created successfully",
      );
    } catch (err) {
      logger.error("Failed to create indexes", {
        error: (err as Error).message,
      });
    }

    const [_unlistedPlaylist, created] = await PlaylistMetadata.findOrCreate({
      where: { playlistUrl: "None" },
      defaults: {
        playlistUrl: "None",
        title: "None",
        monitoringType: "N/A",
        saveDirectory: "",
        lastUpdatedByScheduler: new Date(0),
        sortOrder: -1,
      },
    });

    if (created) {
      logger.info("Unlisted playlist created successfully", {
        host: config.db.host,
        database: config.db.name,
        tables: JSON.stringify([
          PlaylistMetadata.name,
        ]),
      });
    }

    const defaultUserCheck = await UserAccount.count();
    if (defaultUserCheck === 0) {
      logger.warn(
        "No users exist in the database. Please create a user account.",
        { setup_required: true },
      );
    } else {
      logger.info("Users exist in database", {
        user_count: defaultUserCheck,
      });
    }
  } catch (error) {
    logger.error("Unable to create table", { error: error as Error });
  }
}
